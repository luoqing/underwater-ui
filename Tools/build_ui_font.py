#!/usr/bin/env python3
"""Build the standalone WebGL UI font; requires fonttools==4.64.0.

Only glyphs absent from the unchanged Droid source are added. Run with
--check to validate the checked-in font without rewriting any asset.
"""

import argparse
import hashlib
import os
import sys
import tempfile
from pathlib import Path

import fontTools
from fontTools.merge import Merger, Options
from fontTools.subset import Options as SubsetOptions, Subsetter
from fontTools.ttLib import TTFont
from fontTools.ttLib.scaleUpem import scale_upem

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "Assets/Resources/Fonts"
BASE = FONTS / "DroidSansFallbackFull.ttf"
LATIN = FONTS / "LiberationSans-Regular.ttf"
OUTPUT = FONTS / "BlueLanternUI.ttf"
BASE_SHA256 = "acb6440a713d880a13a21b468ba7cd43f5a2b2934972e51be791c880730777b8"
LATIN_SHA256 = "8d91388f1d3604b3b8ae0e3ee2d140e50cd6122f9214514f4aca772540a4076d"
SCRIPTS = [ROOT / "Assets/Scripts/OceanMissions.cs", ROOT / "Assets/Scripts/UnderwaterWorld.cs"]


def validate():
    assert hashlib.sha256(BASE.read_bytes()).hexdigest() == BASE_SHA256, "Original Chinese font changed"
    assert hashlib.sha256(LATIN.read_bytes()).hexdigest() == LATIN_SHA256, "Supplemental source font changed"
    base = TTFont(BASE, recalcTimestamp=False)
    merged = TTFont(OUTPUT, recalcTimestamp=False)
    original_cmap, cmap = base.getBestCmap(), merged.getBestCmap()
    required = set(range(0x20, 0x7F)) | set(map(ord, "·○●←→↑↓海龟第盏距离米"))
    for script in SCRIPTS:
        required.update(ord(character) for character in script.read_text() if character.isprintable())
        assert 'Resources.Load<Font>("Fonts/BlueLanternUI")' in script.read_text(), f"Old font loader in {script}"
    missing = sorted(required - cmap.keys())
    assert not missing, "Missing UI cmap entries: " + " ".join(f"U+{value:04X}" for value in missing)
    assert merged["head"].unitsPerEm == base["head"].unitsPerEm
    # First input glyph names, outlines, hinting and advances must survive unchanged.
    for codepoint, glyph in original_cmap.items():
        assert cmap.get(codepoint) == glyph, f"Original cmap changed: U+{codepoint:04X}"
        assert merged["glyf"][glyph].compile(merged["glyf"]) == base["glyf"][glyph].compile(base["glyf"]), f"Original glyph changed: {glyph}"
        assert merged["hmtx"][glyph] == base["hmtx"][glyph], f"Original advance changed: {glyph}"
    for field in ("ascent", "descent", "lineGap"):
        assert getattr(merged["hhea"], field) == getattr(base["hhea"], field), f"Line metrics changed: {field}"
    print(f"UNDERWATER_UI_FONT_VALIDATED {len(cmap)} direct cmap entries; {len(required)} UI characters; "
          f"{len(original_cmap)} original mappings/outlines/advances unchanged; "
          f"font sha256={hashlib.sha256(OUTPUT.read_bytes()).hexdigest()}")


def build():
    if fontTools.__version__ != "4.64.0":
        raise RuntimeError("Reproducible generation requires fonttools==4.64.0")
    base = TTFont(BASE, recalcTimestamp=False)
    latin = TTFont(LATIN, recalcTimestamp=False)
    options = SubsetOptions()
    options.hinting = False
    options.recalc_timestamp = False
    options.drop_tables.append("FFTM")
    subset = Subsetter(options=options)
    subset.populate(unicodes=set(latin.getBestCmap()) - set(base.getBestCmap()))
    subset.subset(latin)
    # Keep every original CJK glyph and hint instruction byte unchanged.
    scale_upem(latin, base["head"].unitsPerEm)
    with tempfile.TemporaryDirectory(prefix="underwater-ui-font-") as temporary:
        supplemental = Path(temporary) / "missing-latin.ttf"
        latin.save(supplemental)
        merged = Merger(Options(drop_tables=["vhea", "vmtx", "FFTM"])).merge([str(BASE), str(supplemental)])
    merged.recalcTimestamp = False
    merged["head"].created = base["head"].created
    merged["head"].modified = base["head"].modified
    for field in ("ascent", "descent", "lineGap"):
        setattr(merged["hhea"], field, getattr(base["hhea"], field))
    for field in ("sTypoAscender", "sTypoDescender", "sTypoLineGap", "usWinAscent", "usWinDescent"):
        setattr(merged["OS/2"], field, getattr(base["OS/2"], field))
    # The supplemental source reserves "Liberation"; use a new family name.
    names = {
        0: "Digitized data copyright Google Corporation (c) 2006. Digitized data copyright (c) 2010 Google Corporation. Copyright (c) 2012 Red Hat, Inc.",
        1: "Blue Lantern UI", 2: "Regular", 3: "BlueLanternUI-Regular-1.000",
        4: "Blue Lantern UI", 5: "Version 1.000", 6: "BlueLanternUI-Regular",
        13: "SIL Open Font License 1.1. Includes Droid source under Apache License 2.0; see BlueLanternUI-LICENSE.txt.",
        14: "https://openfontlicense.org/", 16: "Blue Lantern UI", 17: "Regular",
        10: "Modified UI font: original Chinese glyphs plus missing Latin and symbol glyphs. Generated by Tools/build_ui_font.py using fontTools 4.64.0.",
    }
    for record in list(merged["name"].names):
        if record.nameID in names:
            merged["name"].setName(names[record.nameID], record.nameID, record.platformID, record.platEncID, record.langID)
    for name_id, text in names.items():
        merged["name"].setName(text, name_id, 3, 1, 0x409)
        merged["name"].setName(text, name_id, 1, 0, 0)
    merged.save(OUTPUT)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate the committed font without regenerating it")
    args = parser.parse_args()
    if not args.check:
        # fontTools' layout merger iterates sets; pin Python's hash seed too.
        if os.environ.get("PYTHONHASHSEED") != "0":
            os.execvpe(sys.executable, [sys.executable, *sys.argv], {**os.environ, "PYTHONHASHSEED": "0"})
        build()
    validate()
